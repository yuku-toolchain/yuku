// inspired by https://github.com/dtolnay/unicode-ident

const std = @import("std");

const unicode_data_url = "https://www.unicode.org/Public/17.0.0/ucd/UCD.zip";
const zip_path = ".zig-cache/ucd.zip";
const extraction_path = ".zig-cache/ucd";
const properties_path = extraction_path ++ "/DerivedCoreProperties.txt";
const output_path = "./src/spec/unicode_id.zig";

const chunk_elements = 16;
const bits_per_element = 32;
const elements_per_chunk = chunk_elements * bits_per_element;
const codepoint_count = std.math.maxInt(u21) + 1;
const chunk_count = codepoint_count / elements_per_chunk;

const CodepointSet = std.bit_set.Dynamic;
const Chunk = [chunk_elements]u32;

pub fn main(init: std.process.Init) !void {
    const gpa = init.gpa;
    const io = init.io;

    var start_set, var continue_set = try downloadAndParseProperties(io, gpa);
    defer start_set.deinit(gpa);
    defer continue_set.deinit(gpa);

    const output = try std.Io.Dir.cwd().createFile(io, output_path, .{});
    defer output.close(io);

    var buffer: [1024]u8 = undefined;
    var file_writer = output.writer(io, &buffer);
    const w = &file_writer.interface;

    try w.writeAll(
        \\// generated by tools/gen_unicode_id.zig, do not edit
        \\//! Unicode ID_Start and ID_Continue, https://www.unicode.org/reports/tr31/
        \\
        \\pub fn canStartId(cp: u32) bool {
        \\    return queryBitTable(cp, &id_start_root, &id_start_leaf);
        \\}
        \\
        \\pub fn canContinueId(cp: u32) bool {
        \\    return queryBitTable(cp, &id_continue_root, &id_continue_leaf);
        \\}
        \\
        \\const chunk_size = 512;
        \\const bits_per_word = 32;
        \\const leaf_chunk_width = 16;
        \\
        \\inline fn queryBitTable(
        \\    cp: u32,
        \\    comptime root: []const u8,
        \\    comptime leaf: []const u64,
        \\) bool {
        \\    const chunk_idx = cp / chunk_size;
        \\    const leaf_base = @as(u32, root[chunk_idx]) * leaf_chunk_width;
        \\    const offset_in_chunk = cp - (chunk_idx * chunk_size);
        \\    const word_idx = leaf_base + (offset_in_chunk / bits_per_word);
        \\    const bit_position: u5 = @truncate(offset_in_chunk % bits_per_word);
        \\    const word = leaf[word_idx];
        \\    return (word >> bit_position) & 1 == 1;
        \\}
        \\
    );
    try writeTables(gpa, w, "id_start", start_set);
    try writeTables(gpa, w, "id_continue", continue_set);
    try file_writer.end();
}

/// Downloads the Unicode data on first use, then returns the ID_Start and ID_Continue sets.
pub fn downloadAndParseProperties(
    io: std.Io,
    gpa: std.mem.Allocator,
) !struct { CodepointSet, CodepointSet } {
    std.Io.Dir.cwd().access(io, properties_path, .{}) catch try fetchUnicodeData(io, gpa);

    const file_data = try std.Io.Dir.cwd().readFileAlloc(
        io,
        properties_path,
        gpa,
        .limited(2 * 1024 * 1024),
    );
    defer gpa.free(file_data);

    var start_set: CodepointSet = try .initEmpty(gpa, codepoint_count);
    errdefer start_set.deinit(gpa);
    var continue_set: CodepointSet = try .initEmpty(gpa, codepoint_count);
    errdefer continue_set.deinit(gpa);

    var lines = std.mem.splitScalar(u8, file_data, '\n');
    while (lines.next()) |line| {
        if (line.len == 0 or line[0] == '#') continue;
        const set = if (std.mem.find(u8, line, "ID_Start") != null)
            &start_set
        else if (std.mem.find(u8, line, "ID_Continue") != null)
            &continue_set
        else
            continue;

        const hex = line[0 .. std.mem.findScalar(u8, line, ' ') orelse line.len];
        const separator = std.mem.find(u8, hex, "..");
        const first = try std.fmt.parseInt(u32, hex[0 .. separator orelse hex.len], 16);
        const last = if (separator) |at| try std.fmt.parseInt(u32, hex[at + 2 ..], 16) else first;
        set.setRangeValue(.{ .start = first, .end = last + 1 }, true);
    }
    return .{ start_set, continue_set };
}

fn writeTables(
    gpa: std.mem.Allocator,
    w: *std.Io.Writer,
    name: []const u8,
    codepoints: CodepointSet,
) !void {
    var leaves: std.array_hash_map.Auto(Chunk, void) = .empty;
    defer leaves.deinit(gpa);

    var root: [chunk_count]u32 = undefined;
    for (&root, 0..) |*leaf_index, chunk_index| {
        var chunk: Chunk = @splat(0);
        for (&chunk, 0..) |*element, element_index| {
            for (0..bits_per_element) |bit_index| {
                const cp = chunk_index * elements_per_chunk +
                    element_index * bits_per_element + bit_index;
                if (codepoints.isSet(cp)) element.* |= @as(u32, 1) << @intCast(bit_index);
            }
        }
        leaf_index.* = @intCast((try leaves.getOrPut(gpa, chunk)).index);
    }
    std.debug.assert(leaves.count() <= 256);

    try writeArray(w, name, "root", "u8", &root, 16);
    const leaf = std.mem.bytesAsSlice(u32, std.mem.sliceAsBytes(leaves.keys()));
    try writeArray(w, name, "leaf", "u64", leaf, 8);
}

fn writeArray(
    w: *std.Io.Writer,
    name: []const u8,
    part: []const u8,
    element_type: []const u8,
    values: []const u32,
    values_per_line: u32,
) !void {
    try w.print("\npub const {s}_{s} = [_]{s}{{", .{ name, part, element_type });
    for (values, 0..) |value, index| {
        try w.writeAll(if (index % values_per_line == 0) "\n    " else " ");
        try w.print("0x{x:0>2},", .{value});
    }
    try w.writeAll("\n};\n");
}

fn fetchUnicodeData(io: std.Io, gpa: std.mem.Allocator) !void {
    var http_client: std.http.Client = .{ .allocator = gpa, .io = io };
    defer http_client.deinit();

    var request = try http_client.request(.GET, try std.Uri.parse(unicode_data_url), .{
        .redirect_behavior = .unhandled,
        .keep_alive = false,
    });
    defer request.deinit();

    try request.sendBodiless();
    var response = try request.receiveHead(&.{});

    const cwd = std.Io.Dir.cwd();
    const zip_file = try cwd.createFile(io, zip_path, .{});
    defer zip_file.close(io);
    defer cwd.deleteFile(io, zip_path) catch @panic("Zip deletion failed");

    var zip_writer = zip_file.writer(io, &.{});
    var response_buffer: [1024]u8 = undefined;
    _ = try response.reader(&response_buffer).streamRemaining(&zip_writer.interface);

    cwd.deleteTree(io, extraction_path) catch {};
    cwd.createDir(io, extraction_path, .default_dir) catch {};

    var extract_dir = try cwd.openDir(io, extraction_path, .{});
    defer extract_dir.close(io);

    const archive = try cwd.openFile(io, zip_path, .{});
    defer archive.close(io);

    var archive_buffer: [1024]u8 = undefined;
    var archive_reader = archive.reader(io, &archive_buffer);
    try std.zip.extract(extract_dir, &archive_reader, .{});
}
