const std = @import("std");
const parser = @import("parser");
const emit = @import("estree/emit.zig");

const lexical = parser.lexical;

const chunk_code_points = 512;
const chunk_bytes = @divExact(chunk_code_points, 8);
const chunk_count = @divExact(0x110000, chunk_code_points);
const chunks_max = 256;

const Chunk = [chunk_bytes]u8;

const Tables = struct {
    chunks: [chunks_max]Chunk,
    chunks_len: u32,
    start: [chunk_count]u8,
    start_len: u32,
    char: [chunk_count]u8,
    char_len: u32,
};

pub fn main(init: std.process.Init) !void {
    try emit.toStdout(init.io, generate);
}

fn generate(w: *std.Io.Writer) std.Io.Writer.Error!void {
    var tables: Tables = undefined;
    build(&tables);

    try w.writeAll("// generated by tools/gen_identifier_tables.zig, do not edit\n\n");
    try writeBase64(w, "START", tables.start[0..tables.start_len]);
    try writeBase64(w, "CHAR", tables.char[0..tables.char_len]);
    try writeBase64(w, "CHUNKS", std.mem.sliceAsBytes(tables.chunks[0..tables.chunks_len]));
}

fn build(tables: *Tables) void {
    tables.chunks[0] = @splat(0);
    tables.chunks_len = 1;
    tables.start_len = 0;
    tables.char_len = 0;
    for (0..chunk_count) |chunk_index| {
        const first: u21 = @intCast(chunk_index * chunk_code_points);
        tables.start[chunk_index] = intern(tables, chunkOf(lexical.isIdentifierStart, first));
        tables.char[chunk_index] = intern(tables, chunkOf(lexical.isIdentifierChar, first));
        if (tables.start[chunk_index] != 0) tables.start_len = @intCast(chunk_index + 1);
        if (tables.char[chunk_index] != 0) tables.char_len = @intCast(chunk_index + 1);
    }
    std.debug.assert(tables.start_len > 0);
    std.debug.assert(tables.char_len >= tables.start_len);
}

fn chunkOf(comptime predicate: fn (u21) bool, first: u21) Chunk {
    var chunk: Chunk = @splat(0);
    for (0..chunk_code_points) |offset| {
        if (predicate(first + @as(u21, @intCast(offset)))) {
            chunk[offset >> 3] |= @as(u8, 1) << @intCast(offset & 7);
        }
    }
    return chunk;
}

fn intern(tables: *Tables, chunk: Chunk) u8 {
    for (tables.chunks[0..tables.chunks_len], 0..) |existing, index| {
        if (std.mem.eql(u8, &existing, &chunk)) return @intCast(index);
    }
    std.debug.assert(tables.chunks_len < chunks_max);
    tables.chunks[tables.chunks_len] = chunk;
    tables.chunks_len += 1;
    return @intCast(tables.chunks_len - 1);
}

fn writeBase64(w: *std.Io.Writer, name: []const u8, bytes: []const u8) !void {
    const encoder = std.base64.standard.Encoder;
    var buffer: [encoder.calcSize(chunks_max * chunk_bytes)]u8 = undefined;
    std.debug.assert(encoder.calcSize(bytes.len) <= buffer.len);
    const text = encoder.encode(&buffer, bytes);

    const line_chars = 92;
    try w.print("export const {s}: string =", .{name});
    var offset: usize = 0;
    while (offset < text.len) : (offset += line_chars) {
        const end = @min(offset + line_chars, text.len);
        const separator = if (end == text.len) ";" else " +";
        try w.print("\n  \"{s}\"{s}", .{ text[offset..end], separator });
    }
    try w.writeAll("\n");
}
