fn isFlagEnum(comptime Field: type) bool {
    return @typeInfo(Field) == .@"enum" and Field != ast.NodeIndex;
}

fn checkOverrides(
    comptime tag: []const u8,
    comptime T: type,
    comptime encode: decoder.Encode,
) void {
    for (encode.fields) |override| {
        if (!@hasField(T, override.field)) {
            @compileError("no field '" ++ override.field ++ "' in " ++ tag);
        }
    }
}

fn overrideOf(comptime encode: decoder.Encode, comptime name: []const u8) ?decoder.Override {
    for (encode.fields) |override| if (eql(override.field, name)) return override;
    return null;
}

fn sourceOf(
    comptime tag: []const u8,
    comptime name: []const u8,
    comptime encode: decoder.Encode,
) []const u8 {
    if (overrideOf(encode, name)) |override| return override.value;
    return "n." ++ decoder.estreeField(tag, name);
}

fn flagValue(
    comptime tag: []const u8,
    comptime T: type,
    comptime index: usize,
    comptime encode: decoder.Encode,
) []const u8 {
    comptime {
        const info = @typeInfo(T).@"struct";
        const name = info.field_names[index];
        const Field = info.field_types[index];
        const source = sourceOf(tag, name, encode);
        const key = decoder.estreeField(tag, name);
        if (Field == bool) return source ++ " === true";
        if (Field == ?ast.ImportPhase) return "_phase(" ++ source ++ ", n)";
        if (Field == ?ast.Hashbang) return source ++ " != null";
        if (overrideOf(encode, name) != null) return source;
        const fallback = if (info.field_attrs[index].defaultValue(Field)) |value|
            std.fmt.comptimePrint("{d}", .{@backingInt(value)})
        else
            "-1";
        return "_enum(" ++ decoder.tableName(Field) ++ ", " ++ source ++ ", " ++ fallback ++
            ", n, \"" ++ key ++ "\")";
    }
}

fn childStatements(
    comptime tag: []const u8,
    comptime name: []const u8,
    comptime Field: type,
    comptime encode: decoder.Encode,
    comptime index: usize,
) []const u8 {
    comptime {
        @setEvalBranchQuota(1_000_000);
        const rule = schema.of(tag, name);
        const source = sourceOf(tag, name, encode);
        const key = "n, \"" ++ decoder.estreeField(tag, name) ++ "\"";
        const role = roleOf(tag, name, rule);
        const f = std.fmt.comptimePrint("f{d}", .{index});
        if (Field == ast.NodeIndex) {
            if (rule.tags.len == 1 and rule.tags[0] == .formal_parameters) {
                return "  const " ++ f ++ " = _params(" ++ source ++ ", " ++ paramsKind(tag) ++
                    ", n);\n";
            }
            if (rule.tags.len == 1) {
                const child = @tagName(rule.tags[0]);
                const v = std.fmt.comptimePrint("v{d}", .{index});
                return "  const " ++ v ++ " = " ++ source ++ ";\n  const " ++ f ++ " = " ++ v ++
                    " == null ? " ++
                    (if (rule.nullable) "-1" else "_missing(" ++ key ++ ")") ++ "\n    : " ++
                    typeCheck(v, decoder.typesOf(child)) ++ " ? _" ++ decoder.pascalName(child) ++
                    "(" ++ v ++ ", " ++ role ++ ") : _wrong(" ++ key ++ ", " ++ v ++ ");\n";
            }
            const v = std.fmt.comptimePrint("v{d}", .{index});
            const check = if (rule.tags.len == 0) "" else "\n  if (" ++ f ++ " >= 0 && " ++
                maskOf(rule) ++ "[_u32[" ++ f ++ " * WORDS] & 255] === 0) _wrong(" ++ key ++ ", " ++
                v ++ ");";
            return "  const " ++ v ++ " = " ++ source ++ ";\n  const " ++ f ++ " = " ++ v ++
                " == null ? " ++ (if (rule.nullable) "-1" else "_missing(" ++ key ++ ")") ++
                "\n    : typeof " ++ v ++ " === \"object\" ? _node(" ++ v ++ ", " ++ role ++
                ") : _wrong(" ++ key ++ ", " ++ v ++ ");" ++ check ++ "\n";
        }
        const count = if (overrideOf(encode, name)) |override| override.count orelse "-1" else "-1";
        const call = if (rule.nullable)
            "_holes(" ++ source ++ ", " ++ role ++ ", " ++ count ++ ", " ++ key ++ ")"
        else if (rule.tags.len == 1) blk: {
            const child = @tagName(rule.tags[0]);
            const child_types = decoder.typesOf(child);
            std.debug.assert(child_types.len == 1);
            break :blk "_listOf(" ++ source ++ ", \"" ++ child_types[0] ++ "\", _" ++
                decoder.pascalName(child) ++ ", " ++ role ++ ", " ++ count ++ ", " ++ key ++ ")";
        } else "_list(" ++ source ++ ", " ++ role ++ ", " ++ count ++ ", " ++ maskOf(rule) ++
            ", " ++ key ++ ")";
        return "  const " ++ f ++ " = " ++ call ++ ", " ++
            std.fmt.comptimePrint("l{d}", .{index}) ++ " = _last;\n";
    }
}

fn typeCheck(comptime value: []const u8, comptime types: []const []const u8) []const u8 {
    comptime {
        std.debug.assert(types.len > 0);
        var check: []const u8 = "";
        for (types, 0..) |estree_type, i| {
            check = check ++ (if (i == 0) "" else " || ") ++ value ++ ".type === \"" ++
                estree_type ++ "\"";
        }
        return "(" ++ check ++ ")";
    }
}

fn paramsKind(comptime tag: []const u8) []const u8 {
    if (eql(tag, "function")) {
        return "ctx === METHOD ? PARAMETER_KINDS.unique_formal_parameters : " ++
            "PARAMETER_KINDS.formal_parameters";
    }
    if (eql(tag, "arrow_function_expression")) return "PARAMETER_KINDS.arrow_formal_parameters";
    return "PARAMETER_KINDS.signature";
}

fn roleOf(
    comptime tag: []const u8,
    comptime name: []const u8,
    comptime rule: schema.Field,
) []const u8 {
    comptime {
        if (@hasField(@TypeOf(roles), tag)) {
            const tag_roles = @field(roles, tag);
            if (@hasField(@TypeOf(tag_roles), name)) return @field(tag_roles, name);
        }
        const has = struct {
            fn has(comptime field: schema.Field, comptime wanted: schema.Tag) bool {
                for (field.tags) |t| if (t == wanted) return true;
                return false;
            }
        }.has;
        if (has(rule, .identifier_reference)) return "ANY";
        if (has(rule, .binding_identifier)) return "BINDING";
        if (has(rule, .identifier_name)) return "NAME";
        if (has(rule, .label_identifier)) return "LABEL";
        if (has(rule, .function_body)) return "BODY";
        return "ANY";
    }
}

fn maskOf(comptime rule: schema.Field) []const u8 {
    comptime {
        @setEvalBranchQuota(1_000_000);
        if (rule.tags.len == 0) return "null";
        var name: []const u8 = "MASK";
        for (rule.tags) |t| name = name ++ std.fmt.comptimePrint("_{d}", .{@backingInt(t)});
        return name;
    }
}

fn writeDispatch(w: *Writer) !void {
    @setEvalBranchQuota(10_000_000);
    var written: [256][]const u8 = undefined;
    var written_len: usize = 0;
    inline for (node_data.field_names, node_data.field_types) |tag, T| {
        if (comptime decoder.typesOf(tag).len == 0) continue;
        const info = @typeInfo(T).@"struct";
        inline for (info.field_names, info.field_types) |name, Field| {
            if (Field != ast.NodeIndex and Field != ast.IndexRange) continue;
            const rule = comptime schema.of(tag, name);
            if (rule.tags.len < 2) continue;
            const mask = comptime maskOf(rule);
            const seen = for (written[0..written_len]) |earlier| {
                if (eql(earlier, mask)) break true;
            } else false;
            if (!seen) {
                written[written_len] = mask;
                written_len += 1;
                try w.print("const {s} = _mask([", .{mask});
                inline for (rule.tags, 0..) |t, i| {
                    try w.print("{s}{d}", .{ if (i == 0) "" else ", ", @backingInt(t) });
                }
                try w.writeAll("]);\n");
            }
        }
    }

    try w.writeAll("function _node(n, ctx) {\n  switch (n.type) {\n");
    const types = comptime estreeTypes();
    inline for (types) |estree_type| {
        const tags = comptime tagsOf(estree_type);
        if (tags.len == 1) {
            try w.print("    case \"{s}\": return _{s}(n, ctx);\n", .{
                estree_type,
                comptime decoder.pascalName(tags[0]),
            });
        } else {
            try w.print("    case \"{s}\": return {s};\n", .{
                estree_type,
                comptime chooserOf(estree_type),
            });
        }
    }
    try w.writeAll("  }\n  return _unknown(n);\n}\n");
}

fn chooserOf(comptime estree_type: []const u8) []const u8 {
    for (choosers) |chooser| if (eql(chooser[0], estree_type)) return chooser[1];
    @compileError("no chooser for " ++ estree_type ++ ", which several tags decode to");
}

fn estreeTypes() []const []const u8 {
    comptime {
        @setEvalBranchQuota(10_000_000);
        var tags: []const []const u8 = &.{};
        for (decoder.inline_kinds) |tag| tags = tags ++ &[_][]const u8{tag};
        for (node_data.field_names) |tag| tags = tags ++ &[_][]const u8{tag};
        var types: []const []const u8 = &.{};
        for (tags) |tag| {
            for (decoder.typesOf(tag)) |estree_type| {
                for (types) |seen| {
                    if (eql(seen, estree_type)) break;
                } else types = types ++ &[_][]const u8{estree_type};
            }
        }
        return types;
    }
}

fn tagsOf(comptime estree_type: []const u8) []const []const u8 {
    comptime {
        var tags: []const []const u8 = &.{};
        for (node_data.field_names) |tag| {
            if (eql(tag, "ts_this_parameter")) continue;
            for (decoder.typesOf(tag)) |t| {
                if (eql(t, estree_type)) tags = tags ++ &[_][]const u8{tag};
            }
        }
        return tags;
    }
}
