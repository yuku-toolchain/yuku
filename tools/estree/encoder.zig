pub fn generate(w: *Writer) Writer.Error!void {
    @setEvalBranchQuota(10_000_000);
    try w.print(
        \\// generated by tools/estree/encoder.zig, do not edit
        \\const WORDS = {[stride]d};
        \\const TAGS = {[tags]d};
        \\const ANY = 0, BINDING = 1, NAME = 2, LABEL = 3, BODY = 4, METHOD = 5;
        \\
    , .{ .stride = stride, .tags = node_data.field_names.len });
    try writeTables(w);
    try writeRuntime(w);
    inline for (node_data.field_names, 0..) |tag, index| {
        try writeEncoder(w, tag, index);
    }
    try writeDispatch(w);
    try w.writeAll("export { encode };\n");
}

fn writeTables(w: *Writer) !void {
    inline for (decoder.tables) |table| {
        if (comptime !isEncodedEnum(table[1])) continue;
        try w.print("const {s} = {{ __proto__: null", .{table[0]});
        inline for (comptime std.enums.values(table[1]), 0..) |value, i| {
            try w.print(", {s}: {d}", .{ comptime decoder.tableItem(value), i });
        }
        try w.writeAll(" };\n");
    }
    inline for (enums) |entry| {
        try w.print("const {s} = {{", .{entry[0]});
        inline for (comptime std.enums.values(entry[1]), 0..) |value, i| {
            const separator = if (i == 0) "" else ",";
            try w.print("{s} {s}: {d}", .{ separator, @tagName(value), @backingInt(value) });
        }
        try w.writeAll(" };\n");
    }
}

fn isEncodedEnum(comptime E: type) bool {
    comptime {
        @setEvalBranchQuota(1_000_000);
        for (node_data.field_types) |T| {
            for (@typeInfo(T).@"struct".field_types) |Field| {
                if (Field == E) return true;
                if (Field == ?E) return true;
            }
        }
        return false;
    }
}

fn writeRuntime(w: *Writer) !void {
    const Comment = rt.PackedComment;
    try w.print(
        \\const COMMENT_WORDS = {[comment_words]d};
        \\const COMMENT_POSITIONS = {{ __proto__: null, before: 0, after: 1, inside: 2 }};
        \\const LEGACY_OCTAL = /^0[0-7]+$/;
        \\const NODES_MIN = 4096, RETAINED_MAX = 1 << 24;
        \\let _u32 = new Int32Array(NODES_MIN * WORDS), _count = 0;
        \\let _extras = new Int32Array(NODES_MIN), _extrasLen = 0, _last = 0;
        \\let _units = new Uint16Array(NODES_MIN * 8), _poolLen = 0;
        \\let _comments = new Int32Array(64 * COMMENT_WORDS), _commentsLen = 0;
        \\let _objects = null, _ts = false;
        \\function encode(root, ts, keep) {{
        \\  _count = 0; _extrasLen = 0; _poolLen = 0; _commentsLen = 0;
        \\  _objects = keep ? [] : null;
        \\  _ts = ts;
        \\  try {{
        \\    if (root === null || typeof root !== "object") _unknown(root);
        \\    _node(root, ANY);
        \\    const nodes = _u32.subarray(0, _count * WORDS);
        \\    const extras = _extras.subarray(0, _extrasLen);
        \\    const comments = _comments.subarray(0, _commentsLen * COMMENT_WORDS);
        \\    const pool = _units.subarray(0, _poolLen);
        \\    if (!keep) return {{ nodes, extras, comments, pool, objects: null }};
        \\    return {{
        \\      nodes: nodes.slice(),
        \\      extras: extras.slice(),
        \\      comments: comments.slice(),
        \\      pool: pool.slice(),
        \\      objects: _objects,
        \\    }};
        \\  }} finally {{
        \\    _objects = null;
        \\    if (_u32.length > RETAINED_MAX) _u32 = new Int32Array(NODES_MIN * WORDS);
        \\    if (_extras.length > RETAINED_MAX) _extras = new Int32Array(NODES_MIN);
        \\    if (_units.length > RETAINED_MAX) _units = new Uint16Array(NODES_MIN * 8);
        \\  }}
        \\}}
        \\function _grow(array, needed) {{
        \\  const grown = new array.constructor(Math.max(array.length * 2, needed));
        \\  grown.set(array);
        \\  return grown;
        \\}}
        \\function _comment(n, i) {{
        \\  const list = n.comments;
        \\  if (list === null || list.length === 0) return;
        \\  if (!Array.isArray(list)) _wrong(n, "comments", list);
        \\  for (let k = 0; k < list.length; k++) {{
        \\    const c = list[k];
        \\    if (c === null || typeof c !== "object") _wrong(n, "comments", c);
        \\    const type = c.type === "Block" ? 1
        \\      : c.type === "Line" ? 0 : _wrong(c, "type", c.type);
        \\    const position = c.position === undefined ? 0 : COMMENT_POSITIONS[c.position];
        \\    if (position === undefined) _wrong(c, "position", c.position);
        \\    const value = c.value;
        \\    if (typeof value !== "string") _wrong(c, "value", value);
        \\    const b = _commentsLen++ * COMMENT_WORDS;
        \\    if (b === _comments.length) _comments = _grow(_comments, b + COMMENT_WORDS);
        \\    const u = _comments;
        \\    u[b] = (type << {[type_bit]d}) | (position << {[position]d}) |
        \\      ((c.sameLine === true) << {[same_line]d});
        \\    u[b + {[comment_node]d}] = i;
        \\    u[b + {[value_start]d}] = _poolLen;
        \\    _pool(value);
        \\    u[b + {[value_start]d} + 1] = _poolLen;
        \\  }}
        \\}}
        \\function _pool(s) {{
        \\  const len = s.length, at = _poolLen;
        \\  if (at + len > _units.length) _units = _grow(_units, at + len);
        \\  const units = _units;
        \\  for (let k = 0; k < len; k++) units[at + k] = s.charCodeAt(k);
        \\  _poolLen = at + len;
        \\}}
        \\function _reserve(len) {{
        \\  const start = _extrasLen;
        \\  _extrasLen = start + len;
        \\  if (_extrasLen > _extras.length) _extras = _grow(_extras, _extrasLen);
        \\  return start;
        \\}}
        \\function _items(list, count, n, key) {{
        \\  if (list === undefined || list === null) return 0;
        \\  if (!Array.isArray(list)) _wrong(n, key, list);
        \\  return count < 0 ? list.length : count;
        \\}}
        \\function _list(list, ctx, count, mask, n, key) {{
        \\  const len = _items(list, count, n, key), start = _reserve(len);
        \\  for (let k = 0; k < len; k++) {{
        \\    const item = list[k];
        \\    if (item === null || typeof item !== "object") _wrong(n, key, item);
        \\    const index = _node(item, ctx);
        \\    if (mask !== null && mask[_u32[index * WORDS] & 255] === 0) _wrong(n, key, item);
        \\    _extras[start + k] = index;
        \\  }}
        \\  _last = len;
        \\  return start;
        \\}}
        \\function _holes(list, ctx, count, n, key) {{
        \\  const len = _items(list, count, n, key), start = _reserve(len);
        \\  for (let k = 0; k < len; k++) {{
        \\    const item = list[k];
        \\    let index = -1;
        \\    if (item !== null && item !== undefined) {{
        \\      if (typeof item !== "object") _wrong(n, key, item);
        \\      index = _node(item, ctx);
        \\    }}
        \\    _extras[start + k] = index;
        \\  }}
        \\  _last = len;
        \\  return start;
        \\}}
        \\function _listOf(list, type, write, ctx, count, n, key) {{
        \\  const len = _items(list, count, n, key), start = _reserve(len);
        \\  for (let k = 0; k < len; k++) {{
        \\    const item = list[k];
        \\    if (item === null || item === undefined || item.type !== type) _wrong(n, key, item);
        \\    const index = write(item, ctx);
        \\    _extras[start + k] = index;
        \\  }}
        \\  _last = len;
        \\  return start;
        \\}}
        \\function _mask(tags) {{
        \\  const mask = new Uint8Array(TAGS);
        \\  for (const tag of tags) mask[tag] = 1;
        \\  return mask;
        \\}}
        \\function _restOf(list) {{
        \\  if (!Array.isArray(list) || list.length === 0) return null;
        \\  const last = list[list.length - 1];
        \\  if (last === null || typeof last !== "object") return null;
        \\  return last.type === "RestElement" ? last : null;
        \\}}
        \\function _params(list, kind, n) {{
        \\  const rest = _restOf(list);
        \\  const len = _items(list, rest === null ? -1 : list.length - 1, n, "params");
        \\  const start = _reserve(len);
        \\  for (let k = 0; k < len; k++) {{
        \\    const p = list[k];
        \\    if (p === null || typeof p !== "object") _wrong(n, "params", p);
        \\    let index;
        \\    if (p.type === "TSParameterProperty") {{
        \\      index = _TSParameterProperty(p, BINDING);
        \\    }} else {{
        \\      const pattern = p.type === "Identifier" && p.name === "this"
        \\        ? _TSThisParameter(p, BINDING) : _node(p, BINDING);
        \\      index = _writeFormalParameter(pattern);
        \\      const b = index * WORDS, from = pattern * WORDS;
        \\      _u32[b + {[ss]d}] = _u32[from + {[ss]d}];
        \\      _u32[b + {[se]d}] = _u32[from + {[se]d}];
        \\    }}
        \\    _extras[start + k] = index;
        \\  }}
        \\  const restIndex = rest === null ? -1 : _BindingRestElement(rest, BINDING);
        \\  const i = _writeFormalParameters(start, len, restIndex, kind), b = i * WORDS;
        \\  _u32[b + {[ss]d}] = 0;
        \\  _u32[b + {[se]d}] = 0;
        \\  return i;
        \\}}
        \\function _literal(n) {{
        \\  switch (typeof n.value) {{
        \\    case "string": return _StringLiteral(n, ANY);
        \\    case "number": return _NumericLiteral(n, ANY);
        \\    case "boolean": return _BooleanLiteral(n, ANY);
        \\    case "bigint": return _BigintLiteral(n, ANY);
        \\  }}
        \\  if (n.regex !== null && n.regex !== undefined) return _RegexpLiteral(n, ANY);
        \\  if (typeof n.bigint === "string") return _BigintLiteral(n, ANY);
        \\  if (typeof n.raw === "string" && n.raw !== "null") return _NumericLiteral(n, ANY);
        \\  return _NullLiteral(n, ANY);
        \\}}
        \\function _spellsNumber(raw, value) {{
        \\  if (String(value) === raw) return !Object.is(value, -0);
        \\  const digits = raw.indexOf("_") === -1 ? raw : raw.replace(/_/g, "");
        \\  if (LEGACY_OCTAL.test(digits)) return Object.is(parseInt(digits, 8), value);
        \\  return Object.is(+digits, value);
        \\}}
        \\function _numericRaw(n) {{
        \\  const value = n.value, raw = n.raw;
        \\  if (typeof value !== "number") {{
        \\    return typeof raw === "string" ? raw : _wrong(n, "value", value);
        \\  }}
        \\  if (typeof raw === "string" && _spellsNumber(raw, value)) return raw;
        \\  return (value < 0 || Object.is(value, -0) ? "-" : "") + String(Math.abs(value));
        \\}}
        \\function _numericKind(raw) {{
        \\  if (raw.charCodeAt(0) !== 48) return NUMERIC_KINDS.decimal;
        \\  switch (raw.charCodeAt(1) | 32) {{
        \\    case 120: return NUMERIC_KINDS.hex;
        \\    case 111: return NUMERIC_KINDS.octal;
        \\    case 98: return NUMERIC_KINDS.binary;
        \\  }}
        \\  return LEGACY_OCTAL.test(raw) ? NUMERIC_KINDS.octal : NUMERIC_KINDS.decimal;
        \\}}
        \\function _bigintRaw(n) {{
        \\  const raw = n.raw;
        \\  const digits = typeof n.bigint === "string" ? n.bigint
        \\    : typeof n.value === "bigint" ? String(n.value) : _wrong(n, "bigint", n.bigint);
        \\  if (typeof raw === "string" && raw.endsWith("n")) {{
        \\    const spelled = raw.slice(0, -1);
        \\    if (BigInt(spelled.replace(/_/g, "")).toString() === digits) return spelled;
        \\  }}
        \\  return digits;
        \\}}
        \\function _object(n, key) {{
        \\  const value = n[key];
        \\  if (value === null || typeof value !== "object") _wrong(n, key, value);
        \\  return value;
        \\}}
        \\function _regexFlags(n, regex) {{
        \\  const flags = regex.flags, raw = typeof n.raw === "string" ? n.raw : "";
        \\  if (typeof flags !== "string") _wrong(n, "regex", regex);
        \\  const rawFlags = raw.slice(raw.lastIndexOf("/") + 1);
        \\  if (rawFlags === flags || rawFlags.split("").sort().join("") === flags) return rawFlags;
        \\  return flags;
        \\}}
        \\function _templateSpan(u, b, tail) {{
        \\  const start = u[b + {[ss]d}] + 1, end = u[b + {[se]d}] - (tail ? 1 : 2);
        \\  if (end < start) return;
        \\  u[b + {[ss]d}] = start;
        \\  u[b + {[se]d}] = end;
        \\}}
        \\function _modifier(n, key, none) {{
        \\  const value = n[key];
        \\  if (value === none || value === undefined) return MAPPED_MODIFIERS.none;
        \\  if (value === true) return MAPPED_MODIFIERS.true;
        \\  if (value === "+") return MAPPED_MODIFIERS.plus;
        \\  if (value === "-") return MAPPED_MODIFIERS.minus;
        \\  return _wrong(n, key, value);
        \\}}
        \\function _enum(table, value, fallback, n, key) {{
        \\  if (value === undefined && fallback >= 0) return fallback;
        \\  const index = table[value];
        \\  return index === undefined ? _wrong(n, key, value) : index;
        \\}}
        \\function _phase(value, n) {{
        \\  if (value === null || value === undefined) return 0;
        \\  return 1 | (_enum(IMPORT_PHASES, value, -1, n, "phase") << 1);
        \\}}
        \\function _describe(v) {{
        \\  if (v !== null && typeof v === "object" && typeof v.type === "string") return v.type;
        \\  return v === null ? "null" : typeof v === "string" ? JSON.stringify(v) : typeof v;
        \\}}
        \\function _missing(n, key) {{
        \\  throw new TypeError(`\`${{n.type}}.${{key}}\` must be a node`);
        \\}}
        \\function _wrong(n, key, v) {{
        \\  throw new TypeError(`\`${{n.type}}.${{key}}\` cannot be ${{_describe(v)}}`);
        \\}}
        \\function _unknown(n) {{
        \\  throw new TypeError(`${{_describe(n)}} is not a node`);
        \\}}
        \\
    , .{
        .comment_words = decoder.words(Comment),
        .ss = decoder.word(rt.PackedNode, "span_start"),
        .se = decoder.word(rt.PackedNode, "span_end"),
        .type_bit = rt.COMMENT_TYPE_BIT,
        .position = rt.COMMENT_POSITION_SHIFT,
        .same_line = rt.COMMENT_SAME_LINE_BIT,
        .comment_node = decoder.word(Comment, "node"),
        .value_start = decoder.word(Comment, "value_start"),
    });
    comptime {
        const value_start = decoder.word(Comment, "value_start");
        std.debug.assert(decoder.word(Comment, "value_end") == value_start + 1);
        std.debug.assert(@offsetOf(rt.PackedNode, "tag") == 0);
        std.debug.assert(@offsetOf(rt.PackedNode, "flags") == 2);
        std.debug.assert(@backingInt(ast.Comment.Position.before) == 0);
        std.debug.assert(@backingInt(ast.Comment.Position.after) == 1);
        std.debug.assert(@backingInt(ast.Comment.Position.inside) == 2);
    }
}

fn writeEncoder(w: *Writer, comptime tag: []const u8, comptime index: usize) !void {
    @setEvalBranchQuota(1_000_000);
    const T = @FieldType(ast.NodeData, tag);
    const info = @typeInfo(T).@"struct";
    const special = comptime decoder.specialOf(tag);
    const encode: decoder.Encode = comptime if (special) |s| s.encode else .{};
    const types = comptime decoder.typesOf(tag);
    const synthetic = types.len == 0;

    if (synthetic) {
        try w.print("function _write{s}(", .{comptime decoder.pascalName(tag)});
        inline for (info.field_names, info.field_types, 0..) |name, Field, i| {
            if (Field == ast.NodeIndex or Field == ast.IndexRange or comptime isFlagEnum(Field)) {
                try w.print("{s}{s}", .{ if (i == 0) "" else ", ", name });
            }
            if (Field == ast.IndexRange) try w.print(", {s}_len", .{name});
        }
        try w.writeAll(") {\n" ++ allocate);
    } else {
        try w.print("function _{s}(n, ctx) {{\n", .{comptime decoder.pascalName(tag)});
        if (encode.prelude.len != 0) try w.print("  {s}\n", .{encode.prelude});
        inline for (info.field_names, info.field_types, 0..) |name, Field, i| {
            if (Field == ast.NodeIndex or Field == ast.IndexRange) {
                try w.writeAll(comptime childStatements(tag, name, Field, encode, i));
            }
        }
        try w.writeAll(allocate);
    }

    try w.print("  u[b] = {d}", .{index});
    inline for (info.field_names, info.field_types, 0..) |name, Field, i| {
        if (Field == bool or Field == ?ast.ImportPhase or Field == ?ast.Hashbang or
            comptime isFlagEnum(Field))
        {
            const at = comptime rt.layout(T, i);
            const value = comptime if (synthetic) name else flagValue(tag, T, i, encode);
            try w.print(" | (({s}) << {d})", .{ value, at.bit + 16 });
        }
    }
    try w.writeAll(";\n");

    inline for (info.field_names, info.field_types, 0..) |name, Field, i| {
        const at = comptime rt.layout(T, i);
        const slot = at.slot + slots_word;
        if (Field == ast.NodeIndex) {
            if (synthetic) {
                try w.print("  u[b + {d}] = {s};\n", .{ slot, name });
            } else {
                try w.print("  u[b + {d}] = f{d};\n", .{ slot, i });
            }
        } else if (Field == ast.IndexRange) {
            if (synthetic) {
                try w.print("  u[b + {d}] = {s}; u[b + {d}] = {s}_len;\n", .{
                    slot,
                    name,
                    slot + 1,
                    name,
                });
            } else {
                try w.print("  u[b + {d}] = f{d}; u[b + {d}] = l{d};\n", .{ slot, i, slot + 1, i });
            }
        } else if (Field == ast.String) {
            comptime std.debug.assert(!synthetic);
            const key = comptime decoder.estreeField(tag, name);
            try w.print(
                \\  const s{[slot]d} = {[source]s};
                \\  if (typeof s{[slot]d} !== "string") _wrong(n, "{[key]s}", s{[slot]d});
                \\  u[b + {[slot]d}] = _poolLen; _pool(s{[slot]d}); u[b + {[end]d}] = _poolLen;
                \\
            , .{
                .slot = slot,
                .end = slot + 1,
                .source = comptime sourceOf(tag, name, encode),
                .key = key,
            });
        } else if (Field == ?ast.Hashbang) {
            const source = comptime sourceOf(tag, name, encode);
            try w.print(
                \\  const h = {[source]s};
                \\  if (h != null) {{
                \\    if (typeof h.value !== "string") _wrong(n, "hashbang", h.value);
                \\    u[b + {[slot]d}] = _poolLen; _pool(h.value); u[b + {[end]d}] = _poolLen;
                \\  }}
                \\
            , .{ .slot = slot, .end = slot + 1, .source = source });
        }
    }
    if (synthetic) {
        try w.writeAll("  return i;\n}\n");
        return;
    }
    try w.print(
        \\  const start = n.start, end = n.end;
        \\  if (start >= 0 && end >= start) {{ u[b + {[ss]d}] = start; u[b + {[se]d}] = end; }}
        \\  else {{ u[b + {[ss]d}] = 0; u[b + {[se]d}] = 0; }}
        \\  if (n.comments !== undefined) _comment(n, i);
        \\  if (_objects !== null) _objects[i] = n;
        \\
    , .{
        .ss = decoder.word(rt.PackedNode, "span_start"),
        .se = decoder.word(rt.PackedNode, "span_end"),
    });
    if (encode.after.len != 0) try w.print("  {s}\n", .{encode.after});
    try w.writeAll("  return i;\n}\n");
    comptime checkOverrides(tag, T, encode);
}

