fn writeEncoder(w: *Writer, comptime tag: []const u8, comptime index: usize) !void {
    @setEvalBranchQuota(1_000_000);
    const T = @FieldType(ast.NodeData, tag);
    const info = @typeInfo(T).@"struct";
    const encode: decoder.Encode = comptime if (decoder.specialOf(tag)) |s| s.encode else .{};
    comptime for (encode.fields) |override| {
        if (@hasField(T, override.field)) continue;
        @compileError("no field '" ++ override.field ++ "' in " ++ tag);
    };
    const synthetic = comptime decoder.typesOf(tag).len == 0;

    if (synthetic) {
        comptime var params: []const []const u8 = &.{};
        inline for (info.field_names, info.field_types) |name, Field| {
            params = params ++ &[_][]const u8{name};
            if (Field == ast.IndexRange) params = params ++ &[_][]const u8{name ++ "_len"};
        }
        try w.writeAll(comptime "function _write" ++ pascalName(tag) ++ "(" ++
            decoder.each(params, "{s}", ", ") ++ ") {\n");
    } else {
        try w.writeAll("function _" ++ comptime pascalName(tag) ++ "(n, ctx, d) {\n");
        if (encode.prelude.len != 0) try w.writeAll("  " ++ encode.prelude ++ "\n");
        inline for (info.field_names, info.field_types, 0..) |name, Field, i| {
            if (Field == ast.NodeIndex or Field == ast.IndexRange) {
                try w.writeAll(comptime childStatements(tag, name, Field, encode, i));
            }
        }
    }
    try w.print(
        \\  const i = _count++, b = i * WORDS;
        \\  if (b === _u32.length) _u32 = _grow(_u32, b + WORDS);
        \\  const u = _u32;
        \\  u[b] = {d}
    , .{index});
    inline for (info.field_names, info.field_types, 0..) |name, Field, i| {
        if (comptime rt.fieldSize(Field).bit == 0) continue;
        const value = comptime if (synthetic) name else flagValue(tag, T, i, encode);
        const bit = comptime rt.layout(T, i).bit + @bitOffsetOf(rt.PackedNode, "flags");
        try w.print(" | (({s}) << {d})", .{ value, bit });
    }
    try w.writeAll(";\n");

    inline for (info.field_names, info.field_types, 0..) |name, Field, i| {
        const slot = comptime rt.layout(T, i).slot + decoder.slots_word;
        const first = comptime if (synthetic) name else std.fmt.comptimePrint("f{d}", .{i});
        const len = comptime if (synthetic) name ++ "_len" else std.fmt.comptimePrint("l{d}", .{i});
        if (Field == ast.NodeIndex) {
            try w.print("  u[b + {d}] = {s};\n", .{ slot, first });
        } else if (Field == ast.IndexRange) {
            try w.print("  u[b + {d}] = {s}; u[b + {d}] = {s};\n", .{ slot, first, slot + 1, len });
        } else if (Field == ast.String) {
            comptime std.debug.assert(!synthetic);
            try w.print(
                \\  const s{[slot]d} = {[source]s};
                \\  if (typeof s{[slot]d} !== "string") _wrong(n, "{[key]s}", s{[slot]d});
                \\  u[b + {[slot]d}] = _poolLen; _pool(s{[slot]d}); u[b + {[end]d}] = _poolLen;
                \\
            , .{
                .slot = slot,
                .end = slot + 1,
                .source = comptime sourceOf(tag, name, encode),
                .key = comptime decoder.estreeField(tag, name),
            });
        } else if (Field == ?ast.Hashbang) {
            try w.print(
                \\  const h = {[source]s};
                \\  if (h != null) {{
                \\    if (typeof h.value !== "string") _wrong(n, "hashbang", h.value);
                \\    u[b + {[slot]d}] = _poolLen; _pool(h.value); u[b + {[end]d}] = _poolLen;
                \\  }}
                \\
            , .{ .slot = slot, .end = slot + 1, .source = comptime sourceOf(tag, name, encode) });
        }
    }
    if (!synthetic) {
        try w.writeAll(finish);
        if (encode.after.len != 0) try w.writeAll("  " ++ encode.after ++ "\n");
    }
    try w.writeAll("  return i;\n}\n");
}

fn overrideOf(comptime encode: decoder.Encode, comptime name: []const u8) ?decoder.Override {
    for (encode.fields) |override| if (eql(override.field, name)) return override;
    return null;
}

fn sourceOf(
    comptime tag: []const u8,
    comptime name: []const u8,
    comptime encode: decoder.Encode,
) []const u8 {
    if (overrideOf(encode, name)) |override| return override.value;
    return "n." ++ decoder.estreeField(tag, name);
}

fn flagValue(
    comptime tag: []const u8,
    comptime T: type,
    comptime index: usize,
    comptime encode: decoder.Encode,
) []const u8 {
    comptime {
        const info = @typeInfo(T).@"struct";
        const name = info.field_names[index];
        const Field = info.field_types[index];
        const source = sourceOf(tag, name, encode);
        if (Field == bool) return source ++ " === true";
        if (Field == ?ast.ImportPhase) return "_phase(" ++ source ++ ", n)";
        if (Field == ?ast.Hashbang) return source ++ " != null";
        if (overrideOf(encode, name) != null) return source;
        const default = info.field_attrs[index].defaultValue(Field);
        return std.fmt.comptimePrint("_enum({s}, {s}, {d}, n, \"{s}\")", .{
            decoder.tableName(Field),
            source,
            if (default) |value| @as(comptime_int, @backingInt(value)) else -1,
            decoder.estreeField(tag, name),
        });
    }
}

fn childStatements(
    comptime tag: []const u8,
    comptime name: []const u8,
    comptime Field: type,
    comptime encode: decoder.Encode,
    comptime index: usize,
) []const u8 {
    comptime {
        @setEvalBranchQuota(1_000_000);
        const rule = schema.of(tag, name);
        const source = sourceOf(tag, name, encode);
        const key = "n, \"" ++ decoder.estreeField(tag, name) ++ "\"";
        const role = roleOf(tag, name, rule);
        const only: ?[]const u8 =
            if (!rule.open and rule.tags.len == 1) @tagName(rule.tags[0]) else null;
        const f = std.fmt.comptimePrint("f{d}", .{index});
        if (Field == ast.IndexRange) {
            const override = overrideOf(encode, name);
            const count = if (override) |o| o.count orelse "-1" else "-1";
            const call = if (rule.nullable)
                "_holes(" ++ source ++ ", " ++ role ++ ", " ++ count
            else if (only) |child| blk: {
                const types = decoder.typesOf(child);
                std.debug.assert(types.len == 1);
                break :blk "_listOf(" ++ source ++ ", \"" ++ types[0] ++ "\", _" ++
                    pascalName(child) ++ ", " ++ role ++ ", " ++ count;
            } else "_list(" ++ source ++ ", " ++ role ++ ", " ++ count ++ ", " ++ maskOf(rule);
            return std.fmt.comptimePrint("  const {s} = {s}, {s}, d), l{d} = _last;\n", .{
                f,
                call,
                key,
                index,
            });
        }
        if (only != null and rule.tags[0] == .formal_parameters) {
            return "  const " ++ f ++ " = _params(" ++ source ++ ", " ++ paramsKind(tag) ++
                ", n, d);\n";
        }
        const v = std.fmt.comptimePrint("v{d}", .{index});
        const present = if (only) |child|
            "(" ++ decoder.each(decoder.typesOf(child), v ++ ".type === \"{s}\"", " || ") ++
                ") ? _" ++ pascalName(child) ++ "(" ++ v ++ ", " ++ role ++ ", d)"
        else
            "typeof " ++ v ++ " === \"object\" ? _node(" ++ v ++ ", " ++ role ++ ", d + 1)";
        const check = if (rule.open or only != null) "" else "\n  if (" ++ f ++ " >= 0 && " ++
            maskOf(rule) ++ "[_u32[" ++ f ++ " * WORDS] & 255] === 0) _wrong(" ++ key ++ ", " ++
            v ++ ");";
        return std.fmt.comptimePrint(
            \\  const {[v]s} = {[source]s};
            \\  const {[f]s} = {[v]s} == null ? {[absent]s}
            \\    : {[present]s} : _wrong({[key]s}, {[v]s});{[check]s}
            \\
        , .{
            .v = v,
            .f = f,
            .source = source,
            .absent = if (rule.nullable) "-1" else "_missing(" ++ key ++ ")",
            .present = present,
            .key = key,
            .check = check,
        });
    }
}

fn paramsKind(comptime tag: []const u8) []const u8 {
    if (eql(tag, "function")) {
        return "ctx === METHOD ? PARAMETER_KINDS.unique_formal_parameters : " ++
            "PARAMETER_KINDS.formal_parameters";
    }
    if (eql(tag, "arrow_function_expression")) return "PARAMETER_KINDS.arrow_formal_parameters";
    return "PARAMETER_KINDS.signature";
}

fn roleOf(
    comptime tag: []const u8,
    comptime name: []const u8,
    comptime rule: schema.Field,
) []const u8 {
    comptime {
        if (@hasField(@TypeOf(roles), tag)) {
            const tag_roles = @field(roles, tag);
            if (@hasField(@TypeOf(tag_roles), name)) return @field(tag_roles, name);
        }
        const Tag = schema.Tag;
        if (std.mem.findScalar(Tag, rule.tags, .identifier_reference) != null) return "ANY";
        if (std.mem.findScalar(Tag, rule.tags, .binding_identifier) != null) return "BINDING";
        if (std.mem.findScalar(Tag, rule.tags, .identifier_name) != null) return "NAME";
        if (std.mem.findScalar(Tag, rule.tags, .label_identifier) != null) return "LABEL";
        if (std.mem.findScalar(Tag, rule.tags, .function_body) != null) return "BODY";
        return "ANY";
    }
}

fn maskOf(comptime rule: schema.Field) []const u8 {
    comptime {
        @setEvalBranchQuota(1_000_000);
        if (rule.open) return "null";
        var name: []const u8 = "MASK";
        for (rule.tags) |t| name = name ++ std.fmt.comptimePrint("_{d}", .{@backingInt(t)});
        return name;
    }
}

fn writeDispatch(w: *Writer) !void {
    @setEvalBranchQuota(10_000_000);
    comptime var masks: []const []const u8 = &.{};
    inline for (tags) |tag| {
        if (comptime decoder.typesOf(tag).len == 0) continue;
        const info = @typeInfo(@FieldType(ast.NodeData, tag)).@"struct";
        inline for (info.field_names, info.field_types) |name, Field| {
            if (Field != ast.NodeIndex and Field != ast.IndexRange) continue;
            const rule = comptime schema.of(tag, name);
            const mask = comptime maskOf(rule);
            if (rule.open or rule.tags.len < 2 or comptime decoder.has(masks, mask)) continue;
            masks = masks ++ &[_][]const u8{mask};
            try w.print("const {s} = _mask([", .{mask});
            inline for (rule.tags, 0..) |t, i| {
                try w.print("{s}{d}", .{ if (i == 0) "" else ", ", @backingInt(t) });
            }
            try w.writeAll("]);\n");
        }
    }

    try w.writeAll("function _node(n, ctx, d) {\n" ++
        "  if (d === RECURSION_MAX) return _spill(n, ctx);\n  switch (n.type) {\n");
    inline for (comptime decoder.estreeTypes(&decoder.inline_kinds ++ tags)) |estree_type| {
        const kinds = comptime tagsOf(estree_type);
        const call = comptime if (kinds.len != 1)
            chooserOf(estree_type)
        else
            "_" ++ pascalName(kinds[0]) ++ "(n, ctx, d)";
        try w.writeAll("    case \"" ++ estree_type ++ "\": return " ++ call ++ ";\n");
    }
    try w.writeAll("  }\n  return _unknown(n);\n}\n");
}

fn chooserOf(comptime estree_type: []const u8) []const u8 {
    for (choosers) |chooser| if (eql(chooser[0], estree_type)) return chooser[1];
    @compileError("no chooser for " ++ estree_type ++ ", which several tags decode to");
}

fn tagsOf(comptime estree_type: []const u8) []const []const u8 {
    comptime {
        var kinds: []const []const u8 = &.{};
        for (tags) |tag| {
            if (eql(tag, "ts_this_parameter")) continue;
            const types = decoder.typesOf(tag);
            if (decoder.has(types, estree_type)) kinds = kinds ++ &[_][]const u8{tag};
        }
        return kinds;
    }
}
