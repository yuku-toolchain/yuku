pub fn specialOf(comptime tag: []const u8) ?Special {
    for (specials) |special| if (eql(special.tag, tag)) return special;
    return null;
}

pub fn typesOf(comptime tag: []const u8) []const []const u8 {
    if (specialOf(tag)) |special| if (special.types) |types| return types;
    return &.{estreeType(tag)};
}

fn typeNames(comptime E: type) []const []const u8 {
    comptime {
        var names: []const []const u8 = &.{};
        for (@typeInfo(E).@"enum".field_names) |name| {
            names = names ++ &[_][]const u8{estreeType(name)};
        }
        return names;
    }
}

fn childKeys(comptime tag: []const u8) []const []const u8 {
    comptime {
        if (specialOf(tag)) |special| if (special.keys) |keys| return keys;
        const info = @typeInfo(@FieldType(ast.NodeData, tag)).@"struct";
        var keys: []const []const u8 = &.{};
        for (info.field_names, info.field_types) |name, Field| {
            if (Field == ast.NodeIndex or Field == ast.IndexRange) {
                keys = keys ++ &[_][]const u8{estreeField(tag, name)};
            }
        }
        return keys;
    }
}

fn nodeBody(comptime tag: []const u8) []const u8 {
    comptime {
        const T = @FieldType(ast.NodeData, tag);
        if (specialOf(tag)) |special| return expand(tag, T, special.body);

        var base: []const u8 = "type: \"" ++ estreeType(tag) ++ "\", start, end";
        var ts: []const u8 = "";
        for (@typeInfo(T).@"struct".field_names, 0..) |name, i| {
            const entry = ", " ++ estreeField(tag, name) ++ ": " ++ fieldValue(tag, T, i);
            if (isTsField(tag, name)) ts = ts ++ entry else base = base ++ entry;
        }
        if (@hasField(@TypeOf(ts_extras), tag)) ts = ts ++ @field(ts_extras, tag);
        if (ts.len == 0) return "return { " ++ base ++ " };";
        return "return _isTs ? { " ++ base ++ ts ++ " } : { " ++ base ++ " };";
    }
}

fn isTsField(comptime tag: []const u8, comptime name: []const u8) bool {
    if (!@hasField(@TypeOf(ts_fields), tag)) return false;
    inline for (@field(ts_fields, tag)) |ts_field| if (comptime eql(ts_field, name)) return true;
    return false;
}

fn expand(comptime tag: []const u8, comptime T: type, comptime template: []const u8) []const u8 {
    comptime {
        @setEvalBranchQuota(100_000);
        var out: []const u8 = "";
        var rest = template;
        while (std.mem.findAny(u8, rest, "@$")) |at| {
            const end = std.mem.findNonePos(u8, rest, at + 1, "abcdefghijklmnopqrstuvwxyz_") orelse
                rest.len;
            const index = field(T, rest[at + 1 .. end]);
            const value = if (rest[at] == '@') fieldValue(tag, T, index) else fieldRaw(T, index);
            out = out ++ rest[0..at] ++ value;
            rest = rest[end..];
        }
        return out ++ rest;
    }
}

fn fieldValue(comptime tag: []const u8, comptime T: type, comptime index: usize) []const u8 {
    const name = @typeInfo(T).@"struct".field_names[index];
    const F = @typeInfo(T).@"struct".field_types[index];
    const at = rt.layout(T, index);
    const s = slotName(at.slot);
    const e = slotName(at.slot + 1);
    const flag = std.fmt.comptimePrint("(flags & {d})", .{1 << at.bit});
    if (F == ast.NodeIndex) {
        if (eql(name, "params")) return s ++ " !== NULL ? fnParams(" ++ s ++ ") : []";
        return s ++ " !== NULL ? node(" ++ s ++ ") : null";
    }
    if (F == ast.IndexRange) {
        const list = if (rt.schema.of(tag, name).nullable) "nodeArrHoles(" else "nodeArr(";
        return list ++ s ++ ", " ++ e ++ ")";
    }
    if (F == ast.String) return "str(" ++ s ++ ", " ++ e ++ ")";
    if (F == bool) return "!!" ++ flag;
    if (F == ?ast.ImportPhase) {
        return flag ++ " ? IMPORT_PHASES[" ++ flagBits(at.bit + 1, 1) ++ "] : null";
    }
    // the hashbang value starts past its `#!`
    if (F == ?ast.Hashbang) return flag ++ " ? { type: \"Hashbang\", start: " ++ s ++
        " - 2, end: " ++ e ++ ", value: str(" ++ s ++ ", " ++ e ++ ") } : null";
    if (@typeInfo(F) == .@"enum") {
        return tableName(F) ++ "[" ++ flagBits(at.bit, rt.enumBitWidth(F)) ++ "]";
    }
    @compileError("unsupported field type in decoder: " ++ @typeName(F));
}

fn fieldRaw(comptime T: type, comptime index: usize) []const u8 {
    const F = @typeInfo(T).@"struct".field_types[index];
    const at = rt.layout(T, index);
    if (F == ast.NodeIndex or F == ast.String) return slotName(at.slot);
    return "(" ++ flagBits(at.bit, rt.enumBitWidth(F)) ++ ")";
}

fn flagBits(comptime bit: u8, comptime width: u8) []const u8 {
    const mask = (1 << width) - 1;
    if (bit == 0) return std.fmt.comptimePrint("flags & {d}", .{mask});
    return std.fmt.comptimePrint("(flags >> {d}) & {d}", .{ bit, mask });
}

fn slotName(comptime slot: u8) []const u8 {
    return std.fmt.comptimePrint("f{d}", .{slot + 1});
}

fn field(comptime T: type, comptime name: []const u8) usize {
    return std.meta.fieldIndex(T, name) orelse
        @compileError("field '" ++ name ++ "' not found in " ++ @typeName(T));
}

pub fn js(comptime text: []const u8, comptime args: anytype) []const u8 {
    comptime {
        @setEvalBranchQuota(10_000_000);
        const path_chars = std.ascii.letters ++ "0123456789_.";
        var out: []const u8 = "";
        var rest = text;
        while (std.mem.cutScalar(u8, rest, '#')) |cut| {
            const path = cut[1][0 .. std.mem.findNone(u8, cut[1], path_chars) orelse cut[1].len];
            out = out ++ cut[0];
            rest = cut[1][path.len..];
            if (@hasField(@TypeOf(args), path)) {
                const value = @field(args, path);
                const is_text = @typeInfo(@TypeOf(value)) == .pointer;
                out = out ++ if (is_text) value else std.fmt.comptimePrint("{d}", .{value});
            } else if (std.mem.cutPrefix(u8, rest, "[i].")) |cell| {
                const column = cell[0 .. std.mem.findNone(u8, cell, path_chars) orelse cell.len];
                const row = .{ fact(path), fact(path ++ "." ++ column) };
                out = out ++ std.fmt.comptimePrint("i * {d} + {d}", row);
                rest = cell[column.len..];
            } else out = out ++ std.fmt.comptimePrint("{d}", .{fact(path)});
        }
        return out ++ rest;
    }
}

fn fact(comptime path: []const u8) comptime_int {
    const root = path[0 .. std.mem.findScalar(u8, path, '.') orelse path.len];
    inline for (.{ rt, rt.semantic, ast }) |namespace| {
        if (@hasDecl(namespace, root)) return member(namespace, path, null);
    }
    @compileError("nothing in the transfer format or the AST is named " ++ path);
}

fn member(comptime T: type, comptime path: []const u8, comptime bytes: ?usize) comptime_int {
    if (path.len == 0) return @divExact(bytes orelse @sizeOf(T), 4);
    const name, const rest = std.mem.cutScalar(u8, path, '.') orelse .{ path, "" };
    if (!@hasDecl(T, name)) {
        return member(@FieldType(T, name), rest, (bytes orelse 0) + @offsetOf(T, name));
    }
    const declaration = @field(T, name);
    return if (@TypeOf(declaration) == type) member(declaration, rest, null) else declaration;
}

pub fn each(
    comptime items: []const []const u8,
    comptime format: []const u8,
    comptime separator: []const u8,
) []const u8 {
    comptime {
        var out: []const u8 = "";
        for (items, 0..) |item, i| {
            out = out ++ (if (i == 0) "" else separator) ++ std.fmt.comptimePrint(format, .{item});
        }
        return out;
    }
}

pub fn has(comptime list: []const []const u8, comptime item: []const u8) bool {
    for (list) |existing| if (eql(existing, item)) return true;
    return false;
}

