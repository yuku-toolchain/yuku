pub fn generate(w: *Writer) Writer.Error!void {
    try w.writeAll(
        \\// generated by tools/estree/decoder.zig, do not edit
        \\const NULL = -1;
        \\const _td = new TextDecoder("utf-8", { ignoreBOM: true });
        \\const BIG_ENDIAN = new Uint8Array(new Uint16Array([1]).buffer)[0] === 0;
        \\function _hostOrder(u32, from, to) {
        \\  for (let i = from; i < to; i++) {
        \\    const v = u32[i];
        \\    u32[i] = (v << 24) | ((v & 0xff00) << 8) | ((v >>> 8) & 0xff00) | (v >>> 24);
        \\  }
        \\}
        \\
    );
    try writeTables(w);
    try writeJSXEntities(w);
    try writeTokenList(w);
    try writeChildTables(w);
    try w.writeAll(
        \\function shaped(shape, start, end, children) {
        \\  const node = Object.assign({ type: shape.type, start, end }, shape.properties);
        \\  const fields = shape.fields, list = shape.list, extra = children.length - fields.length;
        \\  for (let i = 0; i < fields.length; i++) {
        \\    node[fields[i]] = i === list
        \\      ? children.slice(i, i + extra + 1)
        \\      : children[list >= 0 && i > list ? i + extra : i];
        \\  }
        \\  return node;
        \\}
        \\
    );
    try writeKindDecoders(w);
    try writeDecode(w);
    try w.writeAll("export { BindingFlags, decode, TokenKind };\n");
}

pub fn generateWalkTables(w: *Writer) Writer.Error!void {
    @setEvalBranchQuota(1_000_000);
    const merged = comptime mergedChildKeys();
    try w.writeAll(
        \\// generated by tools/estree/decoder.zig, do not edit
        \\import { addChildKeys as ck, childKeys, type ChildVisitor } from "../core/child-keys";
        \\
    );
    inline for (merged) |entry| {
        try w.print("ck(\"{s}\", [", .{entry.type});
        inline for (entry.keys, 0..) |key, i| {
            try w.print("{s}\"{s}\"", .{ if (i == 0) "" else ", ", key });
        }
        try w.writeAll("]);\n");
    }
    try w.writeAll(
        \\ck("Hashbang", []);
        \\
        \\/** The fields of each node type that hold child nodes, in source order. */
        \\export const CHILD_KEYS: Readonly<Record<string, readonly string[]>> = childKeys;
        \\
        \\/** @internal */
        \\export const CHILD_VISITORS: Readonly<Record<string, ChildVisitor>> = {
        \\
    );
    inline for (merged) |entry| {
        if (entry.keys.len == 0) continue;
        try w.print("  {s}: (n, v, s) =>", .{entry.type});
        inline for (entry.keys, 0..) |key, i| {
            try w.print("{s}\n    v(s, n.{s}, \"{s}\")", .{ if (i == 0) "" else " &&", key, key });
        }
        try w.writeAll(",\n");
    }
    try w.writeAll(
        \\};
        \\
        \\const TYPES = [
        \\
    );
    inline for (estree_tags) |tag| {
        inline for (comptime typesOf(tag)) |estree_type| {
            try w.print("  \"{s}\",\n", .{estree_type});
        }
    }
    try w.writeAll(
        \\  "Hashbang",
        \\] as const;
        \\
        \\export type GeneratedNodeType = (typeof TYPES)[number];
        \\
        \\
    );
    try w.writeAll("export const NODE_TYPES: readonly GeneratedNodeType[] = " ++
        "[...new Set<GeneratedNodeType>(TYPES)];\n");
}

const TypeKeys = struct { type: []const u8, keys: []const []const u8 };

fn mergedChildKeys() []const TypeKeys {
    comptime {
        @setEvalBranchQuota(10_000_000);
        var merged: []const TypeKeys = &.{};
        for (estree_tags) |tag| {
            for (typesOf(tag)) |estree_type| {
                var next: []const TypeKeys = &.{};
                var found = false;
                for (merged) |entry| {
                    if (eql(entry.type, estree_type)) {
                        found = true;
                        next = next ++ &[_]TypeKeys{.{
                            .type = entry.type,
                            .keys = withKeys(entry.keys, childKeys(tag)),
                        }};
                    } else {
                        next = next ++ &[_]TypeKeys{entry};
                    }
                }
                if (!found) {
                    next = next ++ &[_]TypeKeys{.{ .type = estree_type, .keys = childKeys(tag) }};
                }
                merged = next;
            }
        }
        return merged;
    }
}

fn withKeys(
    comptime keys: []const []const u8,
    comptime added: []const []const u8,
) []const []const u8 {
    comptime {
        var out = keys;
        for (added) |key| {
            for (out) |existing| {
                if (eql(existing, key)) break;
            } else out = out ++ &[_][]const u8{key};
        }
        return out;
    }
}

