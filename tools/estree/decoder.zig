    const Params = ast.FormalParameters;
    const items = comptime rt.layout(Params, field(Params, "items")).slot + slots_word;
    const ModuleFlags = module_record.Flags;
    try w.writeAll(comptime js(
        \\function decode(buffer, source, path, encoded) {
        \\  const _u8 = new Uint8Array(buffer);
        \\  const _u32 = new Int32Array(buffer, 0, buffer.byteLength >> 2);
        \\  if (BIG_ENDIAN) _hostOrder(_u32, 0, #Header);
        \\  const _src = source;
        \\  const _srcLen = _u32[#Header.source_len];
        \\  const nodeCount = _u32[#Header.node_count],
        \\        extraCount = _u32[#Header.extra_count],
        \\        spLen = _u32[#Header.string_pool_len];
        \\  const commentCount = _u32[#Header.comment_count],
        \\        diagCount = _u32[#Header.diag_count],
        \\        progIdx = _u32[#Header.program_index];
        \\  const tokenCount = _u32[#Header.token_count];
        \\  const _flags = _u32[#Header.flags];
        \\  const _isTs = !!(_flags & #FLAG_TS);
        \\  const _attached = !!(_flags & #FLAG_ATTACHED_COMMENTS);
        \\  const _hasSemantic = !!(_flags & #FLAG_SEMANTIC);
        \\  const _nodesOff = #header_size;
        \\  const eOff = _nodesOff + nodeCount * #node_size;
        \\  const _extraBase = eOff >> 2;
        \\  const _spOff = eOff + extraCount * 4;
        \\  const _cOff = _spOff + ((spLen + 3) & ~3);
        \\  const _tOff = _cOff + commentCount * #comment_size;
        \\  const dOff = _tOff + tokenCount * #token_size;
        \\  // the string pool and the diagnostics are bytes, the other sections 32-bit words
        \\  if (BIG_ENDIAN) {
        \\    _hostOrder(_u32, _nodesOff >> 2, _spOff >> 2);
        \\    _hostOrder(_u32, _cOff >> 2, dOff >> 2);
        \\  }
        \\  function _poolDecode(s, e) {
        \\    const a = _spOff + s - _srcLen, b = _spOff + e - _srcLen;
        \\    let hasEd = false;
        \\    for (let i = a; i < b; i++) if (_u8[i] === 0xED) { hasEd = true; break; }
        \\    if (!hasEd) return _td.decode(_u8.subarray(a, b));
        \\    let r = "";
        \\    for (let i = a; i < b; ) {
        \\      const c = _u8[i];
        \\      if (c < 0x80) { r += String.fromCharCode(c); i++; }
        \\      else if (c < 0xE0) {
        \\        r += String.fromCharCode(((c & 0x1F) << 6) | (_u8[i+1] & 0x3F));
        \\        i += 2;
        \\      }
        \\      else if (c < 0xF0) {
        \\        r += String.fromCharCode(
        \\          ((c & 0x0F) << 12) | ((_u8[i+1] & 0x3F) << 6) | (_u8[i+2] & 0x3F)
        \\        );
        \\        i += 3;
        \\      }
        \\      else {
        \\        r += String.fromCodePoint(
        \\          ((c & 0x07) << 18) | ((_u8[i+1] & 0x3F) << 12) |
        \\            ((_u8[i+2] & 0x3F) << 6) | (_u8[i+3] & 0x3F)
        \\        );
        \\        i += 4;
        \\      }
        \\    }
        \\    return r;
        \\  }
        \\  const str = (s, e) => {
        \\    if (s === e) return "";
        \\    if (s >= _srcLen) return _poolDecode(s, e);
        \\    return _src.slice(s, e);
        \\  };
        \\  function nodeArr(s, len) {
        \\    const r = new Array(len);
