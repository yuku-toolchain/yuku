fn writeKindDecoders(w: *Writer) !void {
    @setEvalBranchQuota(200_000);
    inline for (tags) |tag| {
        if (comptime has(&inline_kinds, tag)) continue;
        try w.writeAll("function _decode" ++ comptime pascalName(tag) ++
            "(decoder, i, b, flags, start, end) {");
        try writeCase(w, tag, true);
    }
    try w.writeAll("const KIND_DECODERS = [\n");
    inline for (tags) |tag| {
        const inlined = comptime has(&inline_kinds, tag);
        const entry = if (inlined) "null" else "_decode" ++ comptime pascalName(tag);
        try w.writeAll("  " ++ entry ++ ",\n");
    }
    try w.writeAll("];\n");
}

fn writeCase(w: *Writer, comptime tag: []const u8, destructure: bool) !void {
    const body = comptime nodeBody(tag);
    var buffer: [256]u8 = undefined;
    var loads: Writer = .fixed(&buffer);
    inline for (0..slots_len) |slot| {
        const name = comptime slotName(slot);
        if (usesIdent(body, name)) {
            const lead = if (loads.end == 0) " const " else ", ";
            try loads.print("{s}{s} = _u32[b + {d}]", .{ lead, name, slot + slots_word });
        }
    }
    if (loads.end != 0) try loads.writeAll(";");

    if (destructure) {
        var first = true;
        for (decoder_fields) |name| {
            if (!usesIdent(loads.buffered(), name) and !usesIdent(body, name)) continue;
            try w.print("{s}{s}", .{ if (first) " const { " else ", ", name });
            first = false;
        }
        if (!first) try w.writeAll(" } = decoder;");
    }
    try w.print("{s} {s} }}\n", .{ loads.buffered(), body });
}

fn isIdentChar(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c == '_' or c == '$';
}

fn usesIdent(body: []const u8, name: []const u8) bool {
    var i: usize = 0;
    while (std.mem.findPos(u8, body, i, name)) |p| : (i = p + 1) {
        const before_ok = p == 0 or !isIdentChar(body[p - 1]);
        const after = p + name.len;
        const after_ok = after >= body.len or !isIdentChar(body[after]);
        if (before_ok and after_ok) return true;
    }
    return false;
}

fn writeDecode(w: *Writer) !void {
