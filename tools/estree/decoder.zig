comptime {
    @setEvalBranchQuota(100_000);
    std.debug.assert(tags.len <= 256);
    std.debug.assert(@offsetOf(rt.PackedNode, "tag") == 0);
    std.debug.assert(@offsetOf(rt.PackedNode, "flags") == 2);
    std.debug.assert(@offsetOf(rt.PackedComment, "flags") == 0);
    for (inline_kinds, 0..) |kind, k| {
