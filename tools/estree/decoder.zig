pub fn generateJSXEntities(w: *Writer) Writer.Error!void {
    const Entity = struct {
        name: []const u8,
        code_point: u16,

        fn lessThan(_: void, a: @This(), b: @This()) bool {
            if (a.code_point != b.code_point) return a.code_point < b.code_point;
            return std.mem.order(u8, a.name, b.name) == .lt;
        }
    };
    const map = spec.jsx_entities.code_points;
    var entities: [map.keys().len]Entity = undefined;
    for (&entities, map.keys(), map.values()) |*entity, name, code_point| {
        entity.* = .{ .name = name, .code_point = code_point };
    }
    std.mem.sort(Entity, &entities, {}, Entity.lessThan);

    var buffer: [4096]u8 = undefined;
    var names: Writer = .fixed(&buffer);
    var previous: ?u16 = null;
    for (entities, 0..) |entity, i| {
        try names.print("{s}{s}", .{ if (i == 0) "" else " ", entity.name });
        const follows = if (previous) |code_point| entity.code_point == code_point + 1 else false;
        if (!follows) try names.print(":{x}", .{entity.code_point});
        previous = entity.code_point;
    }
    try w.writeAll("// generated by tools/estree/decoder.zig, do not edit\n\n");
    try generator.writeString(w, "JSX_ENTITIES", names.buffered());
}

fn writeTables(w: *Writer) !void {
    @setEvalBranchQuota(100_000);
    inline for (tables) |table| {
        try w.print("const {s} = [", .{table[0]});
        inline for (comptime std.enums.values(table[1]), 0..) |value, i| {
            comptime std.debug.assert(@backingInt(value) == i);
            try w.writeAll((if (i == 0) "" else ", ") ++ comptime tableItem(value));
        }
        try w.writeAll("];\n");
    }
    try w.writeAll(
        \\const TS_MAPPED_OPTIONAL = [false, true, "+", "-"];
        \\const TS_MAPPED_READONLY = [null, true, "+", "-"];
        \\const TokenKind = Object.freeze({
        \\
    );
    try writeTokenKinds(w, "  {s}: {d},\n");
    try w.writeAll("});\nconst BindingFlags = Object.freeze({\n");
    const Symbol = semantic.Symbol;
    inline for (@typeInfo(Symbol.Flags).@"struct".field_names) |name| {
        if (comptime eql(name, "_")) continue;
        const overridden = @hasField(@TypeOf(binding_flag_names), name);
        try w.print("  {s}: 1 << {d},\n", .{
            comptime if (overridden) @field(binding_flag_names, name) else snakeConvert(name, true),
            @bitOffsetOf(Symbol.Flags, name),
        });
    }
    inline for (.{
        .{ "Variable", Symbol.variable },
        .{ "Import", Symbol.any_import },
        .{ "ValueSpace", Symbol.value_space },
        .{ "TypeSpace", Symbol.type_space },
        .{ "NamespaceSpace", Symbol.namespace_space },
    }) |group| try w.print("  {s}: {d},\n", .{ group[0], @backingInt(group[1]) });
    try w.writeAll("});\n");
}

pub fn tableItem(comptime value: anytype) []const u8 {
    const E = @TypeOf(value);
    if (E == ast.FunctionType or E == ast.ClassType) return quoted(estreeType(@tagName(value)));
    if (E == ast.Accessibility and value == .none) return "null";
    if (@hasDecl(E, "toString")) return quoted(value.toString());
    return quoted(snakeConvert(@tagName(value), false));
}

pub fn tableName(comptime E: type) []const u8 {
    inline for (tables) |table| if (table[1] == E) return table[0];
    @compileError("no lookup table for enum: " ++ @typeName(E));
}

fn writeTokenKinds(w: *Writer, comptime line: []const u8) !void {
    @setEvalBranchQuota(50_000);
    const info = @typeInfo(ast.TokenTag).@"enum";
    inline for (info.field_names, info.field_values) |name, value| {
        const kind = comptime if (eql(name, "eof")) "EOF" else pascalName(name);
        try w.print(line, .{ kind, value });
    }
}

fn writeTokenList(w: *Writer) !void {
    const Mask = ast.TokenMask;
    const Flag = ast.TokenFlag;
    try w.writeAll(comptime js(
        \\class TokenList {
        \\  constructor(u32, base, count, str) {
        \\    this._u32 = u32;
        \\    this._base = base;
        \\    this.length = count;
        \\    this._str = str;
        \\  }
        \\  _at(i) {
        \\    if (i !== (i | 0) || i < 0 || i >= this.length) throw new RangeError("token " + i);
        \\    return this._base + i * #Token;
        \\  }
        \\  kind(i) { return this._u32[this._at(i) + #Token.tag]; }
        \\  _flags(i) { return this._u32[this._at(i) + #Token.flags]; }
        \\  start(i) { return this._u32[this._at(i) + #Token.span.start]; }
        \\  end(i) { return this._u32[this._at(i) + #Token.span.end]; }
        \\  text(i) {
        \\    const o = this._at(i);
        \\    return this._str(this._u32[o + #Token.span.start], this._u32[o + #Token.span.end]);
        \\  }
        \\  isKeyword(i) { return (this.kind(i) & #TokenMask.IsKeyword) !== 0; }
        \\  isReserved(i) { return (this.kind(i) & #reserved) !== 0; }
        \\  isUnconditionallyReserved(i) { return (this.kind(i) & #TokenMask.IsUnconditionallyReserved) !== 0; }
        \\  isStrictModeReserved(i) { return (this.kind(i) & #TokenMask.IsStrictModeReserved) !== 0; }
        \\  isIdentifierLike(i) { return (this.kind(i) & #TokenMask.IsIdentifierLike) !== 0; }
        \\  isNumericLiteral(i) { return (this.kind(i) & #TokenMask.IsNumericLiteral) !== 0; }
        \\  isBinaryOperator(i) { return (this.kind(i) & #TokenMask.IsBinaryOp) !== 0; }
        \\  isLogicalOperator(i) { return (this.kind(i) & #TokenMask.IsLogicalOp) !== 0; }
        \\  isUnaryOperator(i) { return (this.kind(i) & #TokenMask.IsUnaryOp) !== 0; }
        \\  isAssignmentOperator(i) { return (this.kind(i) & #TokenMask.IsAssignmentOp) !== 0; }
        \\  precedence(i) { return (this.kind(i) >> #TokenMask.PrecShift) & #TokenMask.PrecOverlap; }
        \\  newlineBefore(i) { return (this._flags(i) & #newline) !== 0; }
        \\  escaped(i) { return (this._flags(i) & #escaped) !== 0; }
        \\  invalidEscape(i) { return (this._flags(i) & #invalid) !== 0; }
        \\  loneSurrogate(i) { return (this._flags(i) & #lone) !== 0; }
        \\  _search(column, offset) {
        \\    let lo = 0, hi = this.length;
        \\    while (lo < hi) {
        \\      const mid = (lo + hi) >>> 1;
        \\      if (this._u32[this._base + mid * #Token + column] <= offset)
        \\        lo = mid + 1;
        \\      else hi = mid;
        \\    }
        \\    return lo;
        \\  }
        \\  range(node) {
        \\    const from = this._search(#Token.span.start, node.start - 1);
        \\    const to = this._search(#Token.span.end, node.end);
        \\    return [from, to > from ? to : from];
        \\  }
        \\  before(offset) {
        \\    return this._search(#Token.span.end, offset) - 1;
        \\  }
        \\  after(offset) {
        \\    const i = this._search(#Token.span.start, offset - 1);
        \\    return i < this.length ? i : -1;
        \\  }
        \\  at(offset) {
        \\    const i = this._search(#Token.span.start, offset) - 1;
        \\    return i >= 0 && this.end(i) > offset ? i : -1;
        \\  }
        \\}
        \\
    , .{
        .reserved = Mask.IsUnconditionallyReserved | Mask.IsStrictModeReserved,
        .newline = 1 << @backingInt(Flag.line_terminator_before),
        .escaped = 1 << @backingInt(Flag.escaped),
        .invalid = 1 << @backingInt(Flag.invalid_escape),
        .lone = 1 << @backingInt(Flag.lone_surrogates),
    }));
}

fn writeChildTables(w: *Writer) !void {
    @setEvalBranchQuota(1_000_000);
    try w.writeAll("const CHILD_SLOTS = [\n");
    inline for (tags) |tag| {
        const T = @FieldType(ast.NodeData, tag);
        comptime var slots: []const u8 = "";
        inline for (@typeInfo(T).@"struct".field_types, 0..) |Field, i| {
            if (Field != ast.NodeIndex and Field != ast.IndexRange) continue;
            slots = slots ++ std.fmt.comptimePrint("{s}{d}, {d}", .{
                if (slots.len == 0) "" else ", ",
                @intFromBool(Field == ast.IndexRange),
                comptime rt.layout(T, i).slot + slots_word,
            });
        }
        try w.writeAll("  [" ++ slots ++ "],\n");
    }
    try w.writeAll("];\nconst IS_NODE = [\n");
    inline for (tags) |tag| try w.print("  {},\n", .{comptime typesOf(tag).len != 0});
    try w.writeAll("];\n");
}

