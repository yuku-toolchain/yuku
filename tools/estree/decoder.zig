// ESTree's `JSXText.value` decodes as `lexical.decodeJSXEntities` does.
fn writeJSXEntities(w: *Writer) !void {
    const Entity = struct {
        name: []const u8,
        code_point: u16,

        fn lessThan(_: void, a: @This(), b: @This()) bool {
            if (a.code_point != b.code_point) return a.code_point < b.code_point;
            return std.mem.order(u8, a.name, b.name) == .lt;
        }
    };
    const map = util.XhtmlEntities.code_points;
    var entities: [map.keys().len]Entity = undefined;
    for (&entities, map.keys(), map.values()) |*entity, name, code_point| {
        entity.* = .{ .name = name, .code_point = code_point };
    }
    std.mem.sort(Entity, &entities, {}, Entity.lessThan);

    try w.writeAll("const JSX_ENTITY_NAMES = \"");
    var previous: ?u16 = null;
    for (entities, 0..) |entity, i| {
        try w.print("{s}{s}", .{ if (i == 0) "" else " ", entity.name });
        const follows = if (previous) |code_point| entity.code_point == code_point + 1 else false;
        if (!follows) try w.print(":{x}", .{entity.code_point});
        previous = entity.code_point;
    }
    try w.writeAll(
        \\";
        \\const JSX_ENTITY = /&(?:#x([\da-fA-F]+)|#(\d+)|([\da-zA-Z]+));/g;
        \\let _jsxEntities = null;
        \\function _jsxEntity(name) {
        \\  if (_jsxEntities === null) {
        \\    _jsxEntities = new Map();
        \\    let cp = 0;
        \\    for (const entry of JSX_ENTITY_NAMES.split(" ")) {
        \\      const colon = entry.indexOf(":");
        \\      cp = colon === -1 ? cp + 1 : parseInt(entry.slice(colon + 1), 16);
        \\      _jsxEntities.set(colon === -1 ? entry : entry.slice(0, colon), cp);
        \\    }
        \\  }
        \\  return _jsxEntities.get(name);
        \\}
        \\function _jsxValue(raw) {
        \\  if (raw.indexOf("&") === -1) return raw;
        \\  return raw.replace(JSX_ENTITY, (text, hex, dec, name) => {
        \\    const cp = name === undefined
        \\      ? parseInt(hex === undefined ? dec : hex, hex === undefined ? 10 : 16)
        \\      : _jsxEntity(name);
        \\    return cp === undefined || cp > 0x10ffff ? text : String.fromCodePoint(cp);
        \\  });
        \\}
        \\
    );
}

fn writeTables(w: *Writer) !void {
    @setEvalBranchQuota(100_000);
    inline for (tables) |table| {
        try w.print("const {s} = [", .{table[0]});
        inline for (comptime std.enums.values(table[1]), 0..) |value, i| {
            comptime std.debug.assert(@backingInt(value) == i);
            try w.writeAll((if (i == 0) "" else ", ") ++ comptime tableItem(value));
        }
        try w.writeAll("];\n");
    }
    try w.writeAll(
        \\const TS_MAPPED_OPTIONAL = [false, true, "+", "-"];
        \\const TS_MAPPED_READONLY = [null, true, "+", "-"];
        \\const TokenKind = Object.freeze({
        \\
    );
    try writeTokenKinds(w, "  {s}: {d},\n");
    try w.writeAll("});\nconst BindingFlags = Object.freeze({\n");
    const Symbol = semantic.Symbol;
    inline for (@typeInfo(Symbol.Flags).@"struct".field_names) |name| {
        if (comptime eql(name, "_")) continue;
        try w.print("  {s}: 1 << {d},\n", .{
            @field(binding_flag_names, name),
            @bitOffsetOf(Symbol.Flags, name),
        });
    }
    try w.print(
        \\  Variable: {d},
        \\  Import: {d},
        \\  ValueSpace: {d},
        \\  TypeSpace: {d},
        \\  NamespaceSpace: {d},
        \\}});
        \\
    , .{
        @backingInt(Symbol.variable),
        @backingInt(Symbol.any_import),
        @backingInt(Symbol.value_space),
        @backingInt(Symbol.type_space),
        @backingInt(Symbol.namespace_space),
    });
}

fn tableItem(comptime value: anytype) []const u8 {
    const E = @TypeOf(value);
    if (E == ast.FunctionType or E == ast.ClassType) return quoted(estreeType(@tagName(value)));
    if (E == ast.Accessibility and value == .none) return "null";
    if (@hasDecl(E, "toString")) return quoted(value.toString());
    return quoted(snakeConvert(@tagName(value), false));
}

fn tableName(comptime E: type) []const u8 {
    inline for (tables) |table| if (table[1] == E) return table[0];
    @compileError("no lookup table for enum: " ++ @typeName(E));
}

fn writeTokenKinds(w: *Writer, comptime line: []const u8) !void {
    @setEvalBranchQuota(50_000);
    const info = @typeInfo(ast.TokenTag).@"enum";
    inline for (info.field_names, info.field_values) |name, value| {
        const kind = comptime if (eql(name, "eof")) "EOF" else pascalName(name);
        try w.print(line, .{ kind, value });
    }
}

fn writeTokenList(w: *Writer) !void {
    const Mask = ast.TokenMask;
    try w.print(
        \\class TokenList {{
        \\  constructor(u32, base, count, str) {{
        \\    this._u32 = u32;
        \\    this._base = base;
        \\    this.length = count;
        \\    this._str = str;
        \\  }}
        \\  _at(i) {{
        \\    if (i !== (i | 0) || i < 0 || i >= this.length) throw new RangeError("token " + i);
        \\    return this._base + i * {[stride]d};
        \\  }}
        \\  kind(i) {{ return this._u32[this._at(i) + {[tag]d}]; }}
        \\  _flags(i) {{ return this._u32[this._at(i) + {[flags]d}]; }}
        \\  start(i) {{ return this._u32[this._at(i) + {[start]d}]; }}
        \\  end(i) {{ return this._u32[this._at(i) + {[end]d}]; }}
        \\  text(i) {{
        \\    const o = this._at(i);
        \\    return this._str(this._u32[o + {[start]d}], this._u32[o + {[end]d}]);
        \\  }}
        \\  isKeyword(i) {{ return (this.kind(i) & {[keyword]d}) !== 0; }}
        \\  isReserved(i) {{ return (this.kind(i) & {[reserved]d}) !== 0; }}
        \\  isUnconditionallyReserved(i) {{ return (this.kind(i) & {[unconditional]d}) !== 0; }}
        \\  isStrictModeReserved(i) {{ return (this.kind(i) & {[strict]d}) !== 0; }}
        \\  isIdentifierLike(i) {{ return (this.kind(i) & {[ident]d}) !== 0; }}
        \\  isNumericLiteral(i) {{ return (this.kind(i) & {[numeric]d}) !== 0; }}
        \\  isBinaryOperator(i) {{ return (this.kind(i) & {[binary]d}) !== 0; }}
        \\  isLogicalOperator(i) {{ return (this.kind(i) & {[logical]d}) !== 0; }}
        \\  isUnaryOperator(i) {{ return (this.kind(i) & {[unary]d}) !== 0; }}
        \\  isAssignmentOperator(i) {{ return (this.kind(i) & {[assign]d}) !== 0; }}
        \\  precedence(i) {{ return (this.kind(i) >> {[prec_shift]d}) & {[prec_mask]d}; }}
        \\  newlineBefore(i) {{ return (this._flags(i) & {[newline]d}) !== 0; }}
        \\  escaped(i) {{ return (this._flags(i) & {[escaped]d}) !== 0; }}
        \\  invalidEscape(i) {{ return (this._flags(i) & {[invalid]d}) !== 0; }}
        \\  loneSurrogate(i) {{ return (this._flags(i) & {[lone]d}) !== 0; }}
        \\  _search(column, offset) {{
        \\    let lo = 0, hi = this.length;
        \\    while (lo < hi) {{
        \\      const mid = (lo + hi) >>> 1;
        \\      if (this._u32[this._base + mid * {[stride]d} + column] <= offset)
        \\        lo = mid + 1;
        \\      else hi = mid;
        \\    }}
        \\    return lo;
        \\  }}
        \\  range(node) {{
        \\    const from = this._search({[start]d}, node.start - 1);
        \\    const to = this._search({[end]d}, node.end);
        \\    return [from, to > from ? to : from];
        \\  }}
        \\  before(offset) {{
        \\    return this._search({[end]d}, offset) - 1;
        \\  }}
        \\  after(offset) {{
        \\    const i = this._search({[start]d}, offset - 1);
        \\    return i < this.length ? i : -1;
        \\  }}
        \\  at(offset) {{
        \\    const i = this._search({[start]d}, offset) - 1;
        \\    return i >= 0 && this.end(i) > offset ? i : -1;
        \\  }}
        \\}}
        \\
    , .{
        .stride = words(ast.Token),
        .start = word(ast.Token, "span") + word(ast.Span, "start"),
        .end = word(ast.Token, "span") + word(ast.Span, "end"),
        .tag = word(ast.Token, "tag"),
        .flags = word(ast.Token, "flags"),
        .keyword = Mask.IsKeyword,
        .reserved = Mask.IsUnconditionallyReserved | Mask.IsStrictModeReserved,
        .unconditional = Mask.IsUnconditionallyReserved,
        .strict = Mask.IsStrictModeReserved,
        .ident = Mask.IsIdentifierLike,
        .numeric = Mask.IsNumericLiteral,
        .binary = Mask.IsBinaryOp,
        .logical = Mask.IsLogicalOp,
        .unary = Mask.IsUnaryOp,
        .assign = Mask.IsAssignmentOp,
        .prec_shift = Mask.PrecShift,
        .prec_mask = Mask.PrecOverlap,
        .newline = 1 << @backingInt(ast.TokenFlag.line_terminator_before),
        .escaped = 1 << @backingInt(ast.TokenFlag.escaped),
        .invalid = 1 << @backingInt(ast.TokenFlag.invalid_escape),
        .lone = 1 << @backingInt(ast.TokenFlag.lone_surrogates),
    });
}

fn writeChildTables(w: *Writer) !void {
    @setEvalBranchQuota(1_000_000);
    try w.writeAll("const CHILD_SLOTS = [\n");
    inline for (node_data.field_types) |T| {
        try w.writeAll("  [");
        if (@typeInfo(T) == .@"struct") {
            comptime var first = true;
            inline for (@typeInfo(T).@"struct".field_types, 0..) |Field, i| {
                if (Field == ast.NodeIndex or Field == ast.IndexRange) {
                    try w.print("{s}{d}, {d}", .{
                        if (first) "" else ", ",
                        @intFromBool(Field == ast.IndexRange),
                        comptime rt.layout(T, i).slot + slots_word,
                    });
                    first = false;
                }
            }
        }
        try w.writeAll("],\n");
    }
    try w.writeAll("];\nconst IS_NODE = [\n");
    inline for (node_data.field_names) |tag| {
        try w.print("  {},\n", .{comptime typesOf(tag).len != 0});
    }
    try w.writeAll("];\n");
}

