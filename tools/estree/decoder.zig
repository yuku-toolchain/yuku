pub fn generateWalkTables(w: *Writer) Writer.Error!void {
    try w.writeAll(comptime text: {
        @setEvalBranchQuota(10_000_000);
        var keys: []const u8 = "";
        var visitors: []const u8 = "";
        for (estreeTypes(tags)) |estree_type| {
            const names = keysOf(estree_type);
            keys = keys ++ "\n  " ++ estree_type ++ ": [" ++ each(names, "\"{s}\"", ", ") ++ "],";
            if (names.len == 0) continue;
            visitors = visitors ++ "\n  " ++ estree_type ++ ": (n, v, s) =>" ++
                each(names, "\n    v(s, n.{0s}, \"{0s}\")", " &&") ++ ",";
        }
        var types: []const u8 = "";
        for (tags) |tag| types = types ++ each(typesOf(tag), "\n  \"{s}\",", "");
        break :text js(
            \\// generated by tools/estree/decoder.zig, do not edit
            \\import type { ChildVisitor } from "./walk";
            \\
            \\export const CHILD_KEYS: Record<string, string[]> = {#keys
            \\  Hashbang: [],
            \\};
            \\
            \\export const CHILD_VISITORS: Record<string, ChildVisitor> = {#visitors
            \\};
            \\
            \\const TYPES = [#types
            \\  "Hashbang",
            \\] as const;
            \\
            \\export type GeneratedNodeType = (typeof TYPES)[number];
            \\
            \\export const NODE_TYPES: readonly GeneratedNodeType[] = [...new Set<GeneratedNodeType>(TYPES)];
            \\
        , .{ .keys = keys, .visitors = visitors, .types = types });
    });
}

pub fn estreeTypes(comptime kinds: []const []const u8) []const []const u8 {
    comptime {
        var types: []const []const u8 = &.{};
        for (kinds) |tag| types = unite(types, typesOf(tag));
        return types;
    }
}

fn keysOf(comptime estree_type: []const u8) []const []const u8 {
    comptime {
        var keys: []const []const u8 = &.{};
        for (tags) |tag| {
            if (has(typesOf(tag), estree_type)) keys = unite(keys, childKeys(tag));
        }
        return keys;
    }
}

fn unite(
    comptime list: []const []const u8,
    comptime added: []const []const u8,
) []const []const u8 {
    comptime {
        var out = list;
        for (added) |item| {
            if (!has(out, item)) out = out ++ &[_][]const u8{item};
        }
        return out;
    }
}

